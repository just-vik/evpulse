/**
 * Trip detection state machine states.
 *
 * Модель поездки: одна сессия **D/R → P** (Tesla shift_state). Старт при выходе из парковки
 * (D/R или быстрый старт по скорости); конец при **P** (и отдельно: зарядка / watchdog при потере сигнала).
 *
 * IDLE     — стоит, P или не движется.
 *            → DRIVING при shift D/R или двух подряд точках speed > порога.
 *
 * DRIVING  — активная поездка (передача D/R, поездка не режется по длительной остановке).
 *            → STOPPING при «мягкой» остановке (скорость/мощность).
 *
 * STOPPING — стоит в рамках той же поездки. При shift D/R: выход обратно в DRIVING при движении
 *            (smoothSpeed > 4 или сырая speed > 2 — ползучий выезд из пробки); idle сбрасывается.
 *            Финализация по **P**, зарядке, длинной стоянке в D без P (cap), иначе — эвристики если shift не D/R.
 */
export enum TripState {
  IDLE     = 'IDLE',
  DRIVING  = 'DRIVING',
  STOPPING = 'STOPPING',
}
